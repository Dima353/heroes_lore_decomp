"""Build cpp/src/language_pack_ru.inc from the English and Russian Heroes Lore JARs.

The Russian release differs from the English one only in fonts/, lang/ and fr-FR/ entries.
Those entries are embedded into the port so Russian needs no second JAR at run time.

Usage: python -I tools/make_language_pack.py <english.jar> <russian.jar>
"""
import sys
import zipfile
from pathlib import Path

PREFIXES = ("fonts/", "lang/", "fr-FR/")


def main() -> None:
    english, russian = (zipfile.ZipFile(path) for path in sys.argv[1:3])
    names = sorted(
        name for name in russian.namelist()
        if name.startswith(PREFIXES) and not name.endswith("/")
        and (name not in english.namelist() or russian.read(name) != english.read(name)))
    out = Path(__file__).resolve().parent.parent / "cpp" / "src" / "language_pack_ru.inc"
    lines = ["// Generated by tools/make_language_pack.py from the Russian Heroes Lore JAR. Do not edit."]
    for index, name in enumerate(names):
        data = russian.read(name)
        lines.append(f"static const std::uint8_t ru_file_{index}[] = {{")
        for start in range(0, len(data), 24):
            lines.append("    " + ",".join(str(byte) for byte in data[start:start + 24]) + ",")
        lines.append("};")
    lines.append("static const LanguagePackFile ru_files[] = {")
    for index, name in enumerate(names):
        lines.append(f'    {{"{name}", ru_file_{index}, sizeof(ru_file_{index})}},')
    lines.append("};")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(names)} files -> {out}")


if __name__ == "__main__":
    main()
